"""
Regenerate constraints.txt: the exact versions the image and CI install, taken from the
environment the project was measured in.

    python scripts/update_constraints.py            # write constraints.txt
    python scripts/update_constraints.py --check    # exit 1 if it would change

Without it, `pip install -r requirements.txt` takes whatever the index serves on build day.
On 2026-11-20 that was a different version for 81 of the image's 162 packages, among them
PyMuPDF 1.27.2.3 -> 1.28.2 (the engine whose line model Decisions 89 and 93 are tuned to),
qdrant-client 1.18.0 -> 1.19.1 (Decision 29), litellm 1.89 -> 1.110 and openai 2 -> 3:
the image that would have shipped had never been run.

How: the running interpreter's installed versions (run it with the project's .venv) are the
constraints for `uv pip compile requirements-dev.txt`, resolved as wheels only for Linux
x86_64 and aarch64 on the image's Python. Both resolutions must agree. torch and its CUDA
packages are left out: the Dockerfile (TORCH_VERSION) and CI install the CPU build
separately, at the same pinned version (tests/test_constraints.py checks all of this).
Needs `uv` on PATH.
"""

from __future__ import annotations

import argparse
import importlib.metadata as md
import re
import subprocess
import sys
import tempfile
from pathlib import Path

from packaging.utils import canonicalize_name

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "constraints.txt"
PYTHON = "3.11"  # Dockerfile.hf's python:3.11-slim and CI's setup-python
PLATFORMS = ("x86_64-manylinux_2_28", "aarch64-manylinux_2_28")
# Installed separately (torch, CPU build) or never pinned here (build tools, Windows-only).
EXCLUDED = re.compile(r"^(torch|triton|nvidia-.*|cuda-.*|setuptools|pip|wheel|pywin32|pywin32-ctypes|"
                      r"win32-setctime|colorama)$")

HEADER = """\
# GENERATED by scripts/update_constraints.py — do not edit by hand.
#
# The exact versions the image (Dockerfile.hf) and CI install, via
#   pip install -c constraints.txt -r requirements.txt
# taken from the environment every measurement in DECISIONS_LOG.md / RESULTS.md was made in,
# and resolved as wheels for Linux x86_64 and aarch64 on Python {python}. requirements.txt keeps
# the ranges a change may move within; this file says which point in them was tested.
# torch is pinned separately (Dockerfile.hf TORCH_VERSION, CI), as the CPU build.
#
# To upgrade: upgrade the .venv, re-run the gates and benchmarks, then
#   .venv/Scripts/python scripts/update_constraints.py   (Windows; bin/python elsewhere)
"""


def _venv_pins() -> dict[str, str]:
    pins = {}
    for dist in md.distributions():
        name = canonicalize_name(dist.metadata["Name"])
        if not EXCLUDED.match(name) and "+" not in dist.version:
            pins[name] = dist.version
    return pins


def _resolve(platform: str, constraints: Path) -> dict[str, str]:
    out = subprocess.run(
        ["uv", "pip", "compile", str(ROOT / "requirements-dev.txt"), "-c", str(constraints),
         "--python-platform", platform, "--python-version", PYTHON, "--only-binary", ":all:",
         "--no-header", "--no-annotate", "--quiet"],
        capture_output=True, text=True, cwd=ROOT, timeout=900,
    )
    if out.returncode != 0:
        sys.exit(f"uv could not resolve the measured versions for {platform}:\n{out.stderr}")
    pins = {}
    for line in out.stdout.splitlines():
        m = re.match(r"^([A-Za-z0-9_.\-]+)==([^\s;]+)", line)
        if m:
            pins[canonicalize_name(m.group(1))] = m.group(2)
    return pins


def build() -> str:
    venv = _venv_pins()
    with tempfile.TemporaryDirectory() as tmp:
        constraints = Path(tmp) / "venv.txt"
        constraints.write_text("".join(f"{n}=={v}\n" for n, v in sorted(venv.items())), encoding="utf-8")
        resolved = [_resolve(p, constraints) for p in PLATFORMS]
    keep = [{n: v for n, v in r.items() if not EXCLUDED.match(n)} for r in resolved]
    if keep[0] != keep[1]:
        diff = sorted(set(keep[0].items()) ^ set(keep[1].items()))
        sys.exit(f"x86_64 and aarch64 resolve differently: {diff}")
    lines = [HEADER.format(python=PYTHON)]
    lines += [f"{n}=={v}\n" for n, v in sorted(keep[0].items())]
    return "".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if constraints.txt would change")
    args = parser.parse_args()
    text = build()
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current.replace("\r\n", "\n") != text:
            print("constraints.txt is out of date: run scripts/update_constraints.py")
            return 1
        print("constraints.txt is up to date")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.name}: {text.count(chr(10)) - HEADER.count(chr(10))} pins")
    return 0


if __name__ == "__main__":
    sys.exit(main())
